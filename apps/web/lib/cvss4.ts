export function computeCvss4Score(m: CvssV4Metrics): { score: number; severity: CvssSeverity; vector: string } {
  const key = `${getEQ1(m)}${getEQ2(m)}${getEQ3(m)}${getEQ4(m)}${getEQ5()}`;
  const raw = MACRO_SCORES[key] ?? MACRO_SCORES[`${getEQ1(m)}${getEQ2(m)}${getEQ3(m)}${getEQ4(m)}0`] ?? 5.0;
  const score = Math.round(raw * 10) / 10;

  const severity: CvssSeverity =
    score === 0 ? 'NONE' : score < 4 ? 'LOW' : score < 7 ? 'MEDIUM' : score < 9 ? 'HIGH' : 'CRITICAL';

  const vector = `CVSS:4.0/AV:${m.AV}/AC:${m.AC}/AT:${m.AT}/PR:${m.PR}/UI:${m.UI}/VC:${m.VC}/VI:${m.VI}/VA:${m.VA}/SC:${m.SC}/SI:${m.SI}/SA:${m.SA}`;

  return { score, severity, vector };
}
