export interface CvssV4Metrics {
  AV: 'N' | 'A' | 'L' | 'P';
  AC: 'L' | 'H';
  AT: 'N' | 'P';
  PR: 'N' | 'L' | 'H';
  UI: 'N' | 'P' | 'A';
  VC: 'N' | 'L' | 'H';
  VI: 'N' | 'L' | 'H';
  VA: 'N' | 'L' | 'H';
  SC: 'N' | 'L' | 'H';
  SI: 'N' | 'L' | 'H';
  SA: 'N' | 'L' | 'H';
}

export type CvssSeverity = 'NONE' | 'LOW' | 'MEDIUM' | 'HIGH' | 'CRITICAL';

function getEQ1(m: CvssV4Metrics): number {
  if (m.AV === 'N' && m.PR === 'N' && m.UI === 'N') return 0;
  if ((m.AV === 'N' || m.PR === 'N' || m.UI === 'N') && m.AV !== 'P') return 1;
  return 2;
}
function getEQ2(m: CvssV4Metrics): number {
  return m.AC === 'L' && m.AT === 'N' ? 0 : 1;
}
function getEQ3(m: CvssV4Metrics): number {
  if ((m.VC === 'H' || m.VI === 'H' || m.VA === 'H') && (m.SI === 'H' || m.SA === 'H')) return 0;
  if (m.VC === 'H' || m.VI === 'H' || m.VA === 'H') return 1;
  if (m.SC === 'H' && (m.SI === 'H' || m.SA === 'H')) return 1;
  return 2;
}
function getEQ4(m: CvssV4Metrics): number {
  if (m.SC === 'H' || m.SI === 'H' || m.SA === 'H') return 1;
  return 2;
}
function getEQ5(): number {
  return 0; // Default: Exploit maturity = Attacked
}

